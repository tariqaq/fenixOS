#!/usr/bin/env python3
"""LVGL configuration for the PC simulator, taken from the board's own build.

  python tools/sim_config.py           write board/sim/lv_kconfig.h
  python tools/sim_config.py --check   fail if it differs from the board build (CI board job)

The board configures LVGL through Kconfig (`board/sdkconfig.defaults`). The simulator compiles
LVGL with LV_CONF_KCONFIG_EXTERNAL_INCLUDE pointing at a header holding the same CONFIG_LV_*
values, copied here from board/build/config/sdkconfig.h, so both render identically.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "board" / "build" / "config" / "sdkconfig.h"
OUT = ROOT / "board" / "sim" / "lv_kconfig.h"


def build():
    if not SRC.exists():
        sys.exit("board/build/config/sdkconfig.h missing: build the firmware first (board/idf.ps1 build)")
    lines = [l.strip() for l in SRC.read_text(encoding="utf-8").splitlines()]
    defs = [l for l in lines if l.startswith("#define CONFIG_LV_")]
    return ("/* Generated by tools/sim_config.py from the board build. Do not edit. */\n"
            "#pragma once\n" + "\n".join(defs) + "\n")


def main():
    text = build()
    if "--check" in sys.argv:
        old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if old != text:
            sys.exit("board/sim/lv_kconfig.h is out of date: run python tools/sim_config.py")
        print("sim config ok")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{text.count('#define')} LVGL options -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
