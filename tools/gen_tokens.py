"""Generate the board C header and the PC CSS from design/tokens.json.

Usage: python tools/gen_tokens.py          (write outputs)
       python tools/gen_tokens.py --check  (fail if outputs are stale)
"""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOKENS = json.loads((ROOT / "design/tokens.json").read_text(encoding="utf-8"))
OUT_H = ROOT / "board/components/fenix_ui/include/fenix_tokens.h"
OUT_CSS = ROOT / "app/src/lib/tokens.css"


def c_name(k):
    return k.replace("-", "_").upper()


def header():
    lines = ["// Generated by tools/gen_tokens.py from design/tokens.json. Do not edit.", "#pragma once", "#include <stdint.h>", ""]
    for k, v in TOKENS["color"].items():
        lines.append(f"#define FX_COLOR_{c_name(k)} 0x{v[1:].upper()}u")
    lines.append(f"#define FX_SCRIM_OPA {TOKENS['scrim_opa']}")
    for k, v in TOKENS["radius"].items():
        lines.append(f"#define FX_RADIUS_{c_name(k)} {v}")
    for k in ("fast", "base", "slow"):
        lines.append(f"#define FX_MOTION_{k.upper()}_MS {TOKENS['motion'][k]}")
    for k, v in TOKENS["board"].items():
        lines.append(f"#define FX_{c_name(k)} {v}")
    return "\n".join(lines) + "\n"


def css():
    e = TOKENS["motion"]["ease"]
    lines = ["/* Generated by tools/gen_tokens.py from design/tokens.json. Do not edit. */", ":root {"]
    for k, v in TOKENS["color"].items():
        lines.append(f"  --{k}: {v};")
    lines.append(f"  --scrim: rgba(0, 0, 0, {TOKENS['scrim_opa'] / 255:.2f});")
    for k, v in TOKENS["radius"].items():
        lines.append(f"  --radius-{k}: {v}px;")
    lines.append(f"  --ease: cubic-bezier({e[0]}, {e[1]}, {e[2]}, {e[3]});")
    for k in ("fast", "base", "slow"):
        lines.append(f"  --dur-{k}: {TOKENS['motion'][k]}ms;")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv
    stale = []
    for path, text in ((OUT_H, header()), (OUT_CSS, css())):
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    if stale:
        sys.exit("stale generated files: " + ", ".join(stale) + " (run python tools/gen_tokens.py)")


if __name__ == "__main__":
    main()
