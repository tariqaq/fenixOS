fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

fn render() -> String {
    let mut s = String::from("# name seq hex(wire frame incl trailing 00). Generated by crates/fenix-proto/tests/vectors.rs\n");
    for (i, (name, m)) in samples().iter().enumerate() {
        s += &format!("{name} {} {}\n", i as u8, hex(&m.to_frame(i as u8)));
    }
    s
}

const PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../proto/vectors.txt");

#[test]
fn vectors_match() {
    let want = render();
    if std::env::var("FENIX_REGEN").is_ok() {
        std::fs::write(PATH, &want).unwrap();
    }
    let have = std::fs::read_to_string(PATH).expect("proto/vectors.txt (run with FENIX_REGEN=1 once)").replace("\r\n", "\n");
    assert_eq!(have, want, "proto/vectors.txt is stale");
}

#[test]
fn round_trip() {
    for (i, (name, m)) in samples().into_iter().enumerate() {
        let frame = m.to_frame(i as u8);
        let (seq, back) = Msg::from_frame(&frame[..frame.len() - 1]).unwrap_or_else(|e| panic!("{name}: {e}"));
        assert_eq!(seq, i as u8, "{name}");
        assert_eq!(back, m, "{name}");
    }
}

#[test]
fn decoder_splits_stream_and_skips_garbage() {
    let mut wire = b"ets Jul 29 2019 boot text\r\n".to_vec();
    wire.push(0);
    wire.extend(Msg::Ping(7).to_frame(1));
    wire.extend([0x05, 0x33, 0x00]); // garbage frame
    wire.extend(Msg::Pong(7).to_frame(2));
    let mut d = FrameDecoder::new();
    let mut got = vec![];
    d.push(&wire, |p| got.push(Msg::decode(&p).unwrap().1));
    assert_eq!(got, vec![Msg::Ping(7), Msg::Pong(7)]);
    assert_eq!(d.errors, 2);
}

#[test]
fn rle16() {
    let px: Vec<u16> = std::iter::repeat(0x1234).take(300).chain([1, 2, 2]).collect();
    let enc = rle16_encode(&px);
    let mut back = vec![];
    rle16_decode(&enc, &mut back).unwrap();
    assert_eq!(back, px);
    assert_eq!(enc.len(), 4 * 3);
}
